// Imports the card engine (scripts, frame packs, fonts, images) from a local
// Card Conjurer checkout into web/, converting PNG images to WebP.
//
// Usage: node scripts/import-engine.mjs <path-to-cardconjurer-checkout> [--quality 90]
//
// The engine keeps referring to ".png" paths: web/js/app/assets.js maps them to
// ".webp" at runtime, so frame packs and saved cards stay compatible.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import sharp from 'sharp';

const src = process.argv[2];
if (!src || !fs.existsSync(path.join(src, 'js', 'creator-23.js'))) {
  console.error('Usage: node scripts/import-engine.mjs <cardconjurer-checkout>');
  process.exit(1);
}
const qIdx = process.argv.indexOf('--quality');
const QUALITY = qIdx > 0 ? Number(process.argv[qIdx + 1]) : 90;
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const web = path.join(root, 'web');

// PNGs kept as PNG: the engine compares these names literally.
const KEEP_PNG = new Set(['img/blank.png', 'img/black.png', 'img/blankThumb.png', 'img/blackThumb.png']);
// Folders not used by the creator page.
const SKIP_DIRS = new Set(['img/samples', 'img/tutorial']);

function walk(dir, base = dir, out = []) {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = path.relative(base, full).split(path.sep).join('/');
    const st = fs.statSync(full);
    if (st.isDirectory()) {
      if (!SKIP_DIRS.has(rel)) walk(full, base, out);
    } else out.push(rel);
  }
  return out;
}

function copy(rel) {
  const to = path.join(web, rel);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(path.join(src, rel), to);
}

// 1. Scripts
const scripts = ['js/creator-23.js', 'js/frameSearch.js', 'js/qrious.min.js', 'js/main-1.js'];
for (const f of fs.readdirSync(path.join(src, 'js/frames'))) scripts.push('js/frames/' + f);
scripts.forEach(copy);
console.log('scripts:', scripts.length);

// 1b. Card fonts: keep only the @font-face rules of the original stylesheet.
const css = fs.readFileSync(path.join(src, 'css/style-9.css'), 'utf8');
const faces = (css.match(/@font-face\s*\{[^}]*\}/g) || [])
  // upstream typo: missing extension
  .map((f) => f.replace("fonts/Gill Sans Medium Italic')", "fonts/Gill Sans Medium Italic.otf')"));
fs.mkdirSync(path.join(web, 'css'), { recursive: true });
fs.writeFileSync(path.join(web, 'css/card-fonts.css'),
  '/* Card fonts used by the canvas renderer (generated by scripts/import-engine.mjs). */\n' + faces.join('\n') + '\n');
console.log('font faces:', faces.length);

// 2. Fonts
const fonts = fs.readdirSync(path.join(src, 'fonts')).map((f) => 'fonts/' + f)
  .filter((f) => fs.statSync(path.join(src, f)).isFile());
fonts.forEach(copy);
console.log('fonts:', fonts.length);

// 3. Images
const images = walk(path.join(src, 'img'), src).filter((f) => f.startsWith('img/'));
const toConvert = images.filter((f) => f.toLowerCase().endsWith('.png') && !KEEP_PNG.has(f));
const toCopy = images.filter((f) => !toConvert.includes(f));
toCopy.forEach(copy);
console.log('images copied:', toCopy.length, '| to convert:', toConvert.length);

sharp.concurrency(1);
let done = 0, inBytes = 0, outBytes = 0, skipped = 0;
const queue = toConvert.slice();
async function worker() {
  while (queue.length) {
    const rel = queue.shift();
    const from = path.join(src, rel);
    const to = path.join(web, rel.replace(/\.png$/i, '.webp'));
    fs.mkdirSync(path.dirname(to), { recursive: true });
    const inSize = fs.statSync(from).size;
    if (fs.existsSync(to) && fs.statSync(to).mtimeMs >= fs.statSync(from).mtimeMs) {
      skipped++;
    } else {
      const thumb = /Thumb\.png$/i.test(rel);
      try {
        await sharp(from, { limitInputPixels: false })
          .webp({ quality: thumb ? 82 : QUALITY, alphaQuality: 100, smartSubsample: true, effort: 4 })
          .toFile(to);
      } catch (e) {
        // Unreadable by libvips: ship the original bytes under the .webp name.
        // Browsers pick the image decoder from the file signature, not the name.
        console.warn('\nconvert failed, copying original bytes:', rel, e.message);
        fs.copyFileSync(from, to);
      }
    }
    inBytes += inSize;
    outBytes += fs.statSync(to).size;
    if (++done % 250 === 0) process.stdout.write(`\r${done}/${toConvert.length}`);
  }
}
await Promise.all(Array.from({ length: Math.max(2, os.cpus().length) }, worker));
const mb = (b) => (b / 1048576).toFixed(0) + ' MB';
console.log(`\nconverted ${done} (${skipped} up to date): ${mb(inBytes)} -> ${mb(outBytes)}`);
