// Generates web/js/app/generated.js: offline set codes and keyrune symbol names.
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const web = path.join(root, 'web');

const official = path.join(web, 'img/setSymbols/official');
const codes = new Set();
if (fs.existsSync(official)) {
  for (const f of fs.readdirSync(official)) {
    const m = /^(.+)-(c|u|r|m|s|t)\.(svg|png|webp)$/i.exec(f);
    if (m) codes.add(m[1].toLowerCase());
  }
}
const keyrune = fs.existsSync(path.join(web, 'img/keyrune'))
  ? fs.readdirSync(path.join(web, 'img/keyrune')).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)).sort()
  : [];

const out = '// Generated by scripts/build-data.mjs. Do not edit.\n'
  + 'window.CS_DATA = ' + JSON.stringify({ setCodes: [...codes].sort(), keyrune }) + ';\n';
fs.writeFileSync(path.join(web, 'js/app/generated.js'), out);
console.log('set codes:', codes.size, '| keyrune:', keyrune.length);
